-- ============================================================================
-- Acme Inc. — sample *source* database for AI BI development
-- ============================================================================
--
-- This is the database the app later introspects and reads (never writes).
-- It is destructive by design: re-running drops and recreates the whole
-- `acme` database, so the state after loading is always identical.
--
-- Dev only. Never point this at anything but the local Docker Postgres.
--
-- Load it with:
--   pnpm db:seed
-- See sample-data/README.md for the raw commands and verification queries.

\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------------
-- 1. Reset — always start from a clean slate
-- ---------------------------------------------------------------------------

DROP DATABASE IF EXISTS acme WITH (FORCE);
DROP ROLE IF EXISTS acme_reader;

-- ---------------------------------------------------------------------------
-- 2. The read-only role and the database itself
-- ---------------------------------------------------------------------------
-- acme_reader is the credential the app uses. It can connect and read,
-- nothing else: no writes, no DDL, not even temporary tables.

CREATE ROLE acme_reader LOGIN PASSWORD 'acme_reader_dev'
  NOSUPERUSER NOCREATEDB NOCREATEROLE;

CREATE DATABASE acme OWNER postgres;

REVOKE CONNECT ON DATABASE acme FROM PUBLIC;
REVOKE TEMPORARY ON DATABASE acme FROM PUBLIC;
GRANT CONNECT ON DATABASE acme TO acme_reader;

\connect acme

COMMENT ON DATABASE acme IS
  'Acme Inc. sample source database (dev-only, reloaded by sample-data/seed.sql).';

-- ---------------------------------------------------------------------------
-- 3. Schemas — two domains on purpose, so we never bake in a
--    single-domain assumption (D3)
-- ---------------------------------------------------------------------------

CREATE SCHEMA hr;
CREATE SCHEMA sales;

COMMENT ON SCHEMA hr IS 'People: departments and employees.';
COMMENT ON SCHEMA sales IS 'Commerce: customers, products, orders, order items.';

-- ---------------------------------------------------------------------------
-- 4. HR
-- ---------------------------------------------------------------------------

CREATE TABLE hr.departments (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     text NOT NULL UNIQUE,
  location text
);

COMMENT ON TABLE hr.departments IS 'Company departments.';

CREATE TABLE hr.employees (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id integer REFERENCES hr.departments (id),
  manager_id    integer REFERENCES hr.employees (id),
  first_name    text NOT NULL,
  last_name     text NOT NULL,
  email         text NOT NULL UNIQUE,
  hire_date     date NOT NULL,
  salary        numeric(10, 2) NOT NULL CHECK (salary > 0),
  is_active     boolean NOT NULL DEFAULT true
);

COMMENT ON COLUMN hr.employees.salary IS
  'Annual gross salary (sample amount; currency not modeled).';
COMMENT ON COLUMN hr.employees.manager_id IS
  'Self-reference: the employee''s direct manager.';

CREATE INDEX employees_department_id_idx ON hr.employees (department_id);
CREATE INDEX employees_manager_id_idx ON hr.employees (manager_id);

