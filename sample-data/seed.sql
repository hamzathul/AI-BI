-- Orders and items are generated instead of written out: 120 orders spread
-- deterministically over Jan 2024 – Apr 2026, 1–3 items each. No random() so
-- every reload produces the exact same aggregates.

INSERT INTO sales.orders (customer_id, order_date, status)
SELECT 1 + ((g * 5) % 12),
       DATE '2024-01-08' + ((g * 7) % 900),
       CASE
         WHEN g % 11 = 0 THEN 'cancelled'
         WHEN g % 5 = 0  THEN 'pending'
         WHEN g % 3 = 0  THEN 'paid'
         ELSE 'shipped'
       END
FROM generate_series(1, 120) AS g;

INSERT INTO sales.order_items (order_id, product_id, quantity, unit_price)
SELECT o.id,
       p.id,
       1 + ((o.id + t.n) % 5),
       p.unit_price
FROM sales.orders o
CROSS JOIN LATERAL generate_series(1, (o.id % 3) + 1) AS t(n)
JOIN sales.products p ON p.id = 1 + ((o.id * 7 + t.n) % 15);

-- ---------------------------------------------------------------------------
-- 6. Views — small, opinionated examples for later introspection (2.5)
-- ---------------------------------------------------------------------------

CREATE VIEW hr.department_headcount AS
SELECT d.id   AS department_id,
       d.name AS department,
       count(e.id) AS headcount
FROM hr.departments d
LEFT JOIN hr.employees e
  ON e.department_id = d.id AND e.is_active
GROUP BY d.id, d.name;

CREATE VIEW sales.order_totals AS
SELECT o.id         AS order_id,
       o.order_date,
       c.name       AS customer,
       sum(i.quantity * i.unit_price) AS total
FROM sales.orders o
JOIN sales.customers c ON c.id = o.customer_id
JOIN sales.order_items i ON i.order_id = o.id
WHERE o.status <> 'cancelled'
GROUP BY o.id, o.order_date, c.name;

-- ---------------------------------------------------------------------------
-- 7. Grants — the read-only boundary
-- ---------------------------------------------------------------------------
-- SELECT on everything that exists, plus default privileges so tables added
-- later are readable too. ALTER DEFAULT PRIVILEGES must be run by the role
-- that creates the future objects (postgres here).

GRANT USAGE ON SCHEMA hr, sales TO acme_reader;
GRANT SELECT ON ALL TABLES IN SCHEMA hr, sales TO acme_reader;
ALTER DEFAULT PRIVILEGES IN SCHEMA hr, sales
  GRANT SELECT ON TABLES TO acme_reader;

